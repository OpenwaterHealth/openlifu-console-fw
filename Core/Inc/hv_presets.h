/*
 * hv_presets.h
 *
 * FDA mode: the HV setpoint belongs to the preset, not the host. The image
 * carries one voltage per preset, in the same order as the transmitter
 * image's preset table, so index N names the same preset on both. The host
 * selects an index with OW_POWER_PRESET_SELECT, carrying that preset's
 * settings_crc (CRC-32 of its source .json) so a host holding a different
 * idea of preset N is refused, and the console applies the stored voltage.
 *
 * OW_POWER_SET_HV and the raw DAC commands are refused, HV cannot be turned
 * on until a preset is selected, and the selection cannot change while HV is
 * on.
 *
 * The table is generated by the openlifu SDK (examples/generate_presets.py)
 * into Core/Inc/presets/preset_hv_table.h. Nothing here exists unless
 * the image is built with FDA_MODE.
 */

#ifndef INC_HV_PRESETS_H_
#define INC_HV_PRESETS_H_

#ifdef FDA_MODE

#include "common.h"

#include <stdbool.h>
#include <stdint.h>

// Longest id OW_POWER_PRESET_GET returns, so the reply stays bounded.
#define HV_PRESET_ID_MAX 64u
#define HV_PRESET_NONE 0xFFu

typedef struct {
	const char *id;
	float voltage;          // V, the preset's own value as float32
	uint32_t settings_crc;  // CRC-32 of the source .json, as in the TX image
} HvPreset;

/**
 * @brief  Apply the FDA preset rules to a power command.
 *
 * Answers OW_POWER_PRESET_GET / OW_POWER_PRESET_SELECT and refuses what FDA
 * mode forbids.
 *
 * @return true if cmd was handled here and uartResp filled in; false to let
 *         the normal command processing run.
 */
bool hv_presets_process(UartPacket *uartResp, const UartPacket *cmd);

#endif /* FDA_MODE */

#endif /* INC_HV_PRESETS_H_ */
